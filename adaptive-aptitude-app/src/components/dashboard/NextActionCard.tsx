// src/components/dashboard/NextActionCard.tsx
import React from 'react';
import { ArrowRight, Sparkles, CheckCircle2 } from 'lucide-react';
import type { NextActionDto } from '../../types/api';
import styles from '../../styles/dashboard.module.css';

export interface NextActionCardProps {
  action?: NextActionDto | null;
  onStart: () => void;
  isStarting?: boolean;
}

export const NextActionCard: React.FC<NextActionCardProps> = ({
  action,
  onStart,
  isStarting = false,
}) => {
  if (!action) {
    return (
      <div className={styles.heroCard}>
        <div className={styles.heroHeader}>
          <span style={{ fontSize: 'var(--text-xs)', fontWeight: 600, color: 'var(--status-success)' }}>
            OBJECTIVES UP TO DATE
          </span>
          <CheckCircle2 size={18} color="var(--status-success)" aria-hidden="true" />
        </div>
        <h2 className={styles.heroTitle}>All Caught Up!</h2>
        <p className={styles.heroDescription}>
          You have completed all scheduled prescriptions for your current objectives. Practice any topic from the catalog or take a mock exam.
        </p>
      </div>
    );
  }

  const { actionType, topic, pattern, estimatedMinutes, rationale, executionIntent } = action;
  const displayTitle = `${topic} — ${pattern}`;
  const displayDescription = rationale || executionIntent || 'Prescribed action generated by the adaptive orchestration engine.';

  return (
    <div className={styles.heroCard} data-testid="next-action-card">
      <div className={styles.heroHeader}>
        <div style={{ display: 'flex', alignItems: 'center', gap: '6px' }}>
          <Sparkles size={16} color="var(--accent-primary)" aria-hidden="true" />
          <span
            style={{
              fontSize: 'var(--text-xs)',
              fontWeight: 700,
              color: 'var(--accent-primary)',
              textTransform: 'uppercase',
            }}
          >
            Recommended Next Action
          </span>
        </div>
        {estimatedMinutes && (
          <span style={{ fontSize: 'var(--text-xs)', color: 'var(--text-tertiary)' }}>
            ~{estimatedMinutes} mins
          </span>
        )}
      </div>

      <h2 className={styles.heroTitle}>{displayTitle}</h2>
      <p className={styles.heroDescription}>{displayDescription}</p>

      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', flexWrap: 'wrap', gap: '8px' }}>
        <div style={{ display: 'flex', gap: '6px', fontSize: 'var(--text-xs)', color: 'var(--text-secondary)' }}>
          {actionType && (
            <span style={{ textTransform: 'capitalize', background: 'var(--bg-surface-elevated)', padding: '2px 8px', borderRadius: '4px' }}>
              {actionType.replace(/_/g, ' ')}
            </span>
          )}
          {pattern && (
            <span style={{ background: 'var(--bg-surface-elevated)', padding: '2px 8px', borderRadius: '4px' }}>
              Pattern: {pattern}
            </span>
          )}
        </div>

        <button
          type="button"
          onClick={onStart}
          disabled={isStarting}
          className={`${styles.heroHeader}`}
          style={{
            cursor: isStarting ? 'not-allowed' : 'pointer',
            padding: '8px 18px',
            backgroundColor: 'var(--accent-primary)',
            color: '#ffffff',
            borderRadius: 'var(--radius-md)',
            border: 'none',
            fontSize: 'var(--text-sm)',
            fontWeight: 600,
            display: 'inline-flex',
            alignItems: 'center',
            gap: '8px',
          }}
        >
          <span>{isStarting ? 'Starting...' : 'Start Next Action'}</span>
          <ArrowRight size={16} aria-hidden="true" />
        </button>
      </div>
    </div>
  );
};
